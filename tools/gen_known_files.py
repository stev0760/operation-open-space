"""Generate the asset store's table of known original files (ADR 0002).

Usage:
    re/.venv/bin/python -I tools/gen_known_files.py original.sha256 src/assets/known_files_table.cpp

The manifest is `sha256sum` output with paths relative to the manifest's directory. Every
row under original/shipdisk/ or original/theworks/ becomes one row of the table. Rows under
original/archives/ are skipped, because the asset store never reads archives (ADR 0002). A
row in any other directory is an error, so a new package needs an entry in PACKAGES and in
the Package enum of src/assets/known_files.h.

The manifest hashes the files as shipped. For the 14 SZDD-compressed shipdisk files the
table must also carry the hash of the expanded file, which the manifest does not have. The
generator reads each file from original/ next to the manifest and checks it against the
manifest's hash. It expands SZDD files with re/isre/szdd.py, the code `isre extract` runs,
and takes the installed name from szdd.restored_name. It never reads work/extracted, so a
stale extraction cannot reach the table. original/ must therefore be present.

The output is deterministic: rows are sorted by package and then by installed name, and the
file holds no timestamps and no absolute paths. Running the generator twice gives the same
bytes. tests/test_assets.cpp checks the committed table against original.sha256 and
original/ when they are present.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "re"))

from isre import szdd  # noqa: E402

# Manifest directory -> (Package enumerator, label for the comment). Order = table order.
PACKAGES = {
    "original/shipdisk": ("kShipdisk", "shipdisk v1.29.08"),
    "original/theworks": ("kTheWorks", "theworks"),
}
SKIPPED = ("original/archives",)

OUT_HINT = "src/assets/known_files_table.cpp"


class GenError(Exception):
    pass


def parse_manifest(text: str) -> list[tuple[str, str]]:
    rows = []
    for n, line in enumerate(text.splitlines(), 1):
        if not line.strip():
            continue
        digest, sep, path = line.partition("  ")
        if not sep or len(digest) != 64 or any(c not in "0123456789abcdef" for c in digest):
            raise GenError(f"manifest line {n}: not '<sha256>  <path>'")
        rows.append((digest, path))
    return rows


def c_string(s: str) -> str:
    if not s or any(not (0x20 <= ord(c) < 0x7F) or c in '"\\' for c in s):
        raise GenError(f"name {s!r} is not plain printable ASCII")
    return '"' + s + '"'


def build_rows(manifest: Path) -> list[dict]:
    root = manifest.parent
    rows = []
    seen: dict[tuple[str, str], str] = {}
    for digest, rel in parse_manifest(manifest.read_text(encoding="ascii")):
        directory, _, name = rel.rpartition("/")
        if directory in SKIPPED:
            continue
        if directory not in PACKAGES:
            raise GenError(f"{rel}: no package for directory {directory!r}")
        data = (root / rel).read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise GenError(f"{rel} does not match the manifest")
        header = None
        installed = data
        if szdd.is_szdd(data):
            header = szdd.parse_header(data)
            installed = szdd.expand(data)
        target = szdd.restored_name(name, header)
        key = (directory, target.upper())
        if key in seen:
            raise GenError(f"{rel} and {seen[key]} both restore to {target}")
        seen[key] = rel
        rows.append({
            "package": directory,
            "name": target,
            "size": len(installed),
            "sha256": hashlib.sha256(installed).hexdigest(),
            "dist_name": name,
            "dist_size": len(data),
            "dist_sha256": digest,
        })
    order = list(PACKAGES)
    rows.sort(key=lambda r: (order.index(r["package"]), r["name"].upper(), r["name"]))
    return rows


def render(rows: list[dict], manifest_name: str) -> str:
    out = [
        f"// Generated by tools/gen_known_files.py from {manifest_name}; do not edit. Regenerate with",
        f"//   re/.venv/bin/python -I tools/gen_known_files.py {manifest_name} {OUT_HINT}",
        "// The installed hashes of the SZDD-compressed shipdisk files come from expanding original/",
        "// with re/isre/szdd.py, as the generator's docstring explains. tests/test_assets.cpp checks",
        "// this table against original.sha256 and original/ when they are present.",
        '#include "assets/known_files.h"',
        "",
        "namespace is::assets {",
        "",
        "namespace {",
        "// name, package, size, sha256 (installed); name, size, sha256 (as shipped)",
        "constexpr KnownFile kTable[] = {",
    ]
    current = None
    for r in rows:
        if r["package"] != current:
            current = r["package"]
            out.append(f"    // {PACKAGES[current][1]}")
        out.append(f"    {{{c_string(r['name'])}, Package::{PACKAGES[current][0]}, {r['size']},")
        out.append(f"     \"{r['sha256']}\",")
        out.append(f"     {c_string(r['dist_name'])}, {r['dist_size']},")
        out.append(f"     \"{r['dist_sha256']}\"}},")
    out += [
        "};",
        "}  // namespace",
        "",
        "KnownFiles known_files() { return {kTable, sizeof kTable / sizeof kTable[0]}; }",
        "",
        "}  // namespace is::assets",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: gen_known_files.py MANIFEST OUT", file=sys.stderr)
        return 2
    manifest, out = Path(argv[0]), Path(argv[1])
    try:
        rows = build_rows(manifest)
    except (GenError, OSError, szdd.SzddError) as e:
        print(f"gen_known_files: {e}", file=sys.stderr)
        return 1
    text = render(rows, manifest.name).encode("ascii")
    if not (out.is_file() and out.read_bytes() == text):
        out.write_bytes(text)
    print(f"{len(rows)} rows -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
