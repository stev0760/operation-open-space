"""oracle/probe: isprobe anchors against the unpacked DGROUP images, the MinGW build, argument parsing.

The anchor tests need work/unpacked/ (regenerated by re/isre) and skip without it.
The build test needs i686-w64-mingw32-gcc. The parsing tests build isprobe.c with the host C
compiler, where only --dry-run works, and skip without one."""
from __future__ import annotations

import json
import re
import shutil
import subprocess

import pytest

from conftest import ORACLE, REPO_ROOT, require_tools

SRC = ORACLE / "probe" / "isprobe.c"
BUILD = ORACLE / "probe" / "build.sh"
RUN = ORACLE / "probe" / "probe_run.sh"
UNPACKED = REPO_ROOT / "work" / "unpacked"
# Module name in isprobe.c -> unpacked directory.
MODULE_DIRS = {"INSPACE.EXE": "inspace", "ISPACE.DLL": "ispace"}
ANCHOR_RE = re.compile(r'\{\s*0x(?P<off>[0-9a-f]+),\s*"(?P<hex>[0-9a-f]+)"\s*\}')
MODULE_RE = re.compile(r'\{\s*"(?P<name>[A-Z]+\.[A-Z]+)",\s*"\w+",\s*"\w+",\s*(?P<autodata>\d+),\s*'
                       r'(?P<minalloc>\d+),\s*(?P<arr>\w+),\s*(?P<n>\d+)\s*\}')


def source_modules() -> dict[str, dict]:
    """Module table and anchors as written in isprobe.c."""
    text = SRC.read_text()
    arrays = {}
    for m in re.finditer(r"static const struct anchor (\w+)\[\] = \{(.*?)\n\};", text, re.S):
        arrays[m.group(1)] = [(int(a.group("off"), 16), bytes.fromhex(a.group("hex")))
                              for a in ANCHOR_RE.finditer(m.group(2))]
    mods = {}
    for m in MODULE_RE.finditer(text):
        anchors = arrays[m.group("arr")]
        assert len(anchors) == int(m.group("n")), f"{m.group('name')}: nanchors does not match the array"
        mods[m.group("name")] = {"autodata": int(m.group("autodata")),
                                 "minalloc": int(m.group("minalloc")), "anchors": anchors}
    return mods


def test_source_tables_parse():
    mods = source_modules()
    assert set(mods) == set(MODULE_DIRS)
    for name, mod in mods.items():
        assert len(mod["anchors"]) >= 2, name
        for off, data in mod["anchors"]:
            assert 32 <= len(data) <= 64, (name, hex(off))


def dgroup_image(name: str, autodata: int) -> bytes:
    path = UNPACKED / MODULE_DIRS[name] / f"seg{autodata:02d}.bin"
    if not path.is_file():
        pytest.skip(f"no {path.relative_to(REPO_ROOT)} (regenerate work/ with re/isre)")
    return path.read_bytes()


@pytest.mark.parametrize("name", sorted(MODULE_DIRS))
def test_minalloc_and_autodata_match_unpack_manifest(name):
    mod = source_modules()[name]
    manifest = UNPACKED / MODULE_DIRS[name] / "unpack.json"
    if not manifest.is_file():
        pytest.skip(f"no {manifest.relative_to(REPO_ROOT)}")
    segs = {s["seg"]: s for s in json.loads(manifest.read_text())["segments"]}
    assert max(segs) == mod["autodata"]  # DGROUP is the last segment of both modules
    assert segs[mod["autodata"]]["minalloc"] == mod["minalloc"]
    assert len(dgroup_image(name, mod["autodata"])) == mod["minalloc"]


@pytest.mark.parametrize("name", sorted(MODULE_DIRS))
def test_anchors_are_unique_initialised_bytes(name):
    mods = source_modules()
    mod = mods[name]
    image = dgroup_image(name, mod["autodata"])
    others = [dgroup_image(o, mods[o]["autodata"]) for o in mods if o != name]
    last_init = max(i for i, b in enumerate(image) if b)  # BSS above this is zero-filled at load
    for off, data in mod["anchors"]:
        assert image[off:off + len(data)] == data, f"{name} anchor DGROUP:{off:#x} does not match the image"
        assert image.count(data) == 1, f"{name} anchor DGROUP:{off:#x} occurs {image.count(data)} times"
        assert off + len(data) <= last_init + 1, f"{name} anchor DGROUP:{off:#x} reaches into BSS"
        for other in others:
            assert other.count(data) == 0, f"{name} anchor DGROUP:{off:#x} also occurs in another DGROUP"


def test_run_script_syntax():
    require_tools("bash")
    subprocess.run(["bash", "-n", str(RUN)], check=True)
    # The probe is started by a relative path: Wine 11.0 segfaults on an absolute Unix exe path
    # when no drive maps it (newgame.sh removes Z:), see digest probe-0001.
    assert 'wine work/probe/isprobe.exe' in RUN.read_text()


def test_build_script(tmp_path):
    require_tools("bash")
    subprocess.run(["bash", "-n", str(BUILD)], check=True)
    require_tools("i686-w64-mingw32-gcc")
    out = subprocess.run([str(BUILD), str(tmp_path)], capture_output=True, text=True, check=True)
    exe = tmp_path / "isprobe.exe"
    assert out.stdout.strip() == str(exe)
    assert "warning" not in out.stderr
    data = exe.read_bytes()
    assert data[:2] == b"MZ"
    pe = int.from_bytes(data[0x3c:0x40], "little")
    assert data[pe:pe + 4] == b"PE\0\0"
    assert int.from_bytes(data[pe + 4:pe + 6], "little") == 0x14c  # i386
    opt = pe + 24
    assert int.from_bytes(data[opt:opt + 2], "little") == 0x10b  # PE32
    assert int.from_bytes(data[opt + 68:opt + 70], "little") == 3  # IMAGE_SUBSYSTEM_WINDOWS_CUI
    imports = data.lower()
    assert b"kernel32.dll" in imports and b"user32.dll" in imports
    # Read-only by construction: the probe never imports a write or debug API.
    for api in (b"WriteProcessMemory", b"VirtualProtectEx", b"DebugActiveProcess", b"SetThreadContext",
                b"CreateRemoteThread"):
        assert api not in data


@pytest.fixture(scope="module")
def host_probe(tmp_path_factory):
    cc = shutil.which("cc") or shutil.which("gcc")
    if cc is None:
        pytest.skip("no host C compiler")
    exe = tmp_path_factory.mktemp("isprobe") / "isprobe"
    subprocess.run([cc, "-std=c99", "-O2", "-Wall", "-Wextra", "-Werror", "-o", str(exe), str(SRC)], check=True)

    def run(*args: str) -> subprocess.CompletedProcess:
        return subprocess.run([str(exe), *args], capture_output=True, text=True)
    return run


@pytest.mark.parametrize("args, expect", [
    (["find"], "cmd=find route=scan"),
    (["read", "inspace", "DGROUP:0x9684", "4"], "cmd=read module=INSPACE.EXE off=0x9684 len=4 route=scan"),
    (["read", "ISPACE.DLL", "dgroup:0x10", "0x20"], "cmd=read module=ISPACE.DLL off=0x0010 len=32 route=scan"),
    (["dump", "INSPACE", "DGROUP", "out.bin"], "cmd=dump module=INSPACE.EXE len=41456 out=out.bin route=scan"),
    (["dump", "ispace", "DGROUP", "-"], "cmd=dump module=ISPACE.DLL len=8876 out=- route=scan"),
    (["--sel", "03a7", "dump", "INSPACE.EXE", "DGROUP", "x", "all"],
     "cmd=dump module=INSPACE.EXE len=all out=x route=sel:0x03a7"),
    (["watch", "INSPACE", "DGROUP:0x9320", "2", "100", "50", "--base", "0xcb4950"],
     "cmd=watch module=INSPACE.EXE off=0x9320 len=2 ms=100 count=50 route=base:0x00cb4950"),
    (["--pid", "0x20", "watch", "ISPACE", "DGROUP:0x0", "16", "50", "0"],
     "cmd=watch module=ISPACE.DLL off=0x0000 len=16 ms=50 count=0 route=scan pid=32"),
    (["ldt", "0427"], "cmd=ldt sel=0x0427"),
])
def test_dry_run_parses(host_probe, args, expect):
    r = host_probe("--dry-run", *args)
    assert r.returncode == 0, r.stderr
    assert r.stdout == f"dry-run {expect}\n"


@pytest.mark.parametrize("args", [
    [],
    ["frob"],
    ["find", "extra"],
    ["--sel", "03a7", "find"],
    ["read", "IGRAPHIC", "DGROUP:0x0", "4"],
    ["read", "INSPACE", "0x9684", "4"],
    ["read", "INSPACE", "DGROUP:0xzz", "4"],
    ["read", "INSPACE", "DGROUP:0x9684", "0"],
    ["read", "INSPACE", "DGROUP:0xfff0", "0x20"],
    ["read", "INSPACE", "DGROUP:0x9684"],
    ["dump", "INSPACE", "DGROUP:0x0", "out.bin"],
    ["dump", "INSPACE", "DGROUP", "out.bin", "0x10001"],
    ["watch", "INSPACE", "DGROUP:0x0", "0x1001", "100", "1"],
    ["watch", "INSPACE", "DGROUP:0x0", "2", "0", "1"],
    ["watch", "INSPACE", "DGROUP:0x0", "2", "100", "-1"],
    ["ldt", "03a3"],  # a GDT selector
    ["--sel", "03a7", "--base", "1000", "read", "INSPACE", "DGROUP:0x0", "1"],
    ["--bogus", "find"],
    ["--pid"],
])
def test_dry_run_rejects(host_probe, args):
    r = host_probe("--dry-run", *args)
    assert r.returncode == 2
    assert r.stdout == ""
    assert "usage: isprobe" in r.stderr


def test_host_build_touches_no_process(host_probe):
    r = host_probe("find")
    assert r.returncode == 3
    assert "--dry-run" in r.stderr
